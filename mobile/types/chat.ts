export interface PendingImage {
  url: string;
  width?: number;
  height?: number;
}

export interface ReactionResult {
  action: 'added' | 'removed' | 'changed';
  emoji: string;
  previousEmoji?: string;
  messageId: string;
  senderId: string;
  senderName: string;
}

export interface ChatMessage {
  id: string;
  group_id: string;
  sender_id: string;
  sender_name: string;
  content: string;
  created_at: string;
  reactions?: Record<string, string[]>;
  deleted_at?: string | null;
  edited_at?: string | null;
  reply_to_id?: string | null;
  reply_to_content?: string | null;
  reply_to_sender?: string | null;
  image_url?: string | null;
  image_width?: number | null;
  image_height?: number | null;
  // Idempotency key generated by the sending client. Lets the app match its local "sending"
  // placeholder to the saved row, and lets the server ignore a retried send. Null on older messages.
  client_id?: string | null;
  // 'system' rows are centered notices ("Sam joined the group") written by the server.
  kind?: 'user' | 'system';
  // Set while the message is pinned to the group.
  pinned_at?: string | null;
  pinned_by?: string | null;
  // Clerk ids of the people @mentioned in this message.
  mentions?: string[] | null;
  // Set only on the local placeholder shown while a send is queued/in-flight
  // (offline or slow network) — never present on a message from the server.
  pending?: boolean;
  // Set only on the local placeholder for a send that exhausted its retries —
  // never present on a message from the server.
  failed?: boolean;
  // Identifies the underlying mutation for a pending/failed placeholder so it
  // can be retried or discarded; never present on a message from the server.
  mutationId?: number;
}
